import assert from 'node:assert/strict';
import { test } from 'node:test';
import { CvSourceError, buildCareerData, parseCv, parseRecord, serializeCareer } from './lib/cv-source.mjs';

const CV = `# CV

## Summary

\`\`\`text
First sentence
continues here.
\`\`\`

## Experience

\`\`\`text
Application Specialist
Bosch (Bosch Digital), Warsaw, Poland | Aug 2024 to present

- First bullet
  wrapped onto a second line.
- Second bullet.
\`\`\`

\`\`\`text
Engineer
Sii Poland | Jan 2022 to May 2024

- One bullet.
\`\`\`

## Selected case studies

\`\`\`text
Project One
A summary
that wraps.

- Shipped 9 runs.
\`\`\`

## Skills

\`\`\`text
AI: One, Two,
Three

Data: SQL
\`\`\`

## Education

\`\`\`text
Woolf
MSc AI
Delivered through a programme.
\`\`\`
`;

const RECORD = `# CAREER

## Career record

| Work location | Warsaw, Poland |

Current role start Aug 2024, present. Prior: Jan 2022 to May 2024.

Bosch (Bosch Digital), Sii Poland, Woolf, AI, Data.

## Project inventory

| # | Project | Source | Verified numbers |
| --- | --- | --- | --- |
| P1 | Project One | Course | 9 |
| P2 | Project Two | Course | 4 |

### MSc capstone track

## Certifications (full set, from SRC2)

Udacity Institute of AI & Technology:

| Certificate | Issued |
| --- | --- |
| Cert A | Oct \`2026\` |

Stibo Systems:

| Certificate | Issued |
| --- | --- |
| Cert B | Sep \`2025\` |

ServiceNow (expired / ex-certified):

| Certificate | First issued | Status |
| --- | --- | --- |
| Cert C | Jan \`2023\` | expired |

Other:

| Certificate | Issuer | Issued |
| --- | --- | --- |
| ITIL v4 | PeopleCert | Oct \`2021\` |
| AWS Scholarship | Udacity | Jul \`2020\` |

## Skills ledger
`;

const record = parseRecord(RECORD);

test('parses the CV blocks, joining wrapped bullets and skill lines', () => {
  const cv = parseCv(CV);
  assert.equal(cv.cvSummary, 'First sentence continues here.');
  assert.equal(cv.experience.length, 2);
  assert.deepEqual(cv.experience[0].bullets, [
    'First bullet wrapped onto a second line.',
    'Second bullet.',
  ]);
  assert.equal(cv.experience[1].left, 'Sii Poland');
  assert.equal(cv.cvProjects[0].summary, 'A summary that wraps.');
  assert.deepEqual(cv.skillGroups, [
    { name: 'AI', skills: 'One, Two, Three' },
    { name: 'Data', skills: 'SQL' },
  ]);
  assert.deepEqual(cv.education, [
    { institution: 'Woolf', credential: 'MSc AI', detail: 'Delivered through a programme.' },
  ]);
});

test('reads locations and the current certification selection from the record', () => {
  assert.deepEqual(record.locations, ['Warsaw, Poland']);
  assert.deepEqual(record.certifications, [
    { name: 'Cert A', issuer: 'Udacity Institute of AI & Technology', date: 'Oct 2026' },
    { name: 'Cert B', issuer: 'Stibo Systems', date: 'Sep 2025' },
    { name: 'Cert C', issuer: 'ServiceNow', date: 'Jan 2023', status: 'expired' },
    { name: 'ITIL v4', issuer: 'PeopleCert', date: 'Oct 2021' },
  ]);
});

test('splits the location from the company and omits it when absent', () => {
  const data = buildCareerData(parseCv(CV), record);
  assert.deepEqual(data.experience[0], {
    company: 'Bosch (Bosch Digital)',
    role: 'Application Specialist',
    location: 'Warsaw, Poland',
    period: 'Aug 2024 to present',
    bullets: ['First bullet wrapped onto a second line.', 'Second bullet.'],
  });
  assert.equal('location' in data.experience[1], false);
  assert.equal(data.certifications.length, 4);
});

test('rejects a company the record does not contain', () => {
  const cv = parseCv(CV);
  cv.experience[1].left = 'Unknown Ltd';
  assert.throws(() => buildCareerData(cv, record), CvSourceError);
});

test('rejects a phone-shaped string in the generated data', () => {
  const cv = parseCv(CV);
  cv.cvSummary = 'Call +48 789 495 259 for details.';
  assert.throws(() => buildCareerData(cv, record), CvSourceError);
});

test('serializes a generated header and const exports', () => {
  const output = serializeCareer(buildCareerData(parseCv(CV), record));
  assert.match(output, /^\/\/ Generated by scripts\/sync-cv\.mjs/);
  assert.match(output, /export const experience = \[/);
  assert.match(output, /\] as const;/);
  assert.match(output, /export const cvSummary = "First sentence continues here\."/);
});
